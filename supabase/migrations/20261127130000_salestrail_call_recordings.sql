-- SalesTrail call recordings: every answered call a BDE makes to a lead is
-- pulled from SalesTrail, matched to the lead by phone number, and its audio
-- copied into the private call-recordings bucket by the salestrail_sync edge
-- function, which pg_cron calls every 5 minutes.

create table if not exists public.call_recordings (
    id bigint generated by default as identity primary key,
    created_at timestamp with time zone not null default now(),
    salestrail_call_id text not null,
    sales_id bigint,
    contact_id bigint not null,
    deal_id bigint,
    phone_number text not null,
    is_inbound boolean not null default false,
    started_at timestamp with time zone not null,
    duration_seconds integer not null default 0,
    status text not null default 'pending',
    storage_path text,
    attempts smallint not null default 0,
    last_error text,
    constraint call_recordings_status_check
        check (status in ('pending', 'stored', 'failed'))
);

create table if not exists public.salestrail_sync_state (
    id smallint primary key default 1,
    synced_until timestamp with time zone not null,
    constraint salestrail_sync_state_single_row check (id = 1)
);

alter table only public.call_recordings
    add constraint call_recordings_sales_id_fkey foreign key (sales_id) references public.sales(id) on delete set null;
alter table only public.call_recordings
    add constraint call_recordings_contact_id_fkey foreign key (contact_id) references public.contacts(id) on delete cascade;
alter table only public.call_recordings
    add constraint call_recordings_deal_id_fkey foreign key (deal_id) references public.deals(id) on delete set null;

create unique index if not exists call_recordings_salestrail_call_id_key on public.call_recordings using btree (salestrail_call_id);
create index if not exists call_recordings_deal_id_idx on public.call_recordings using btree (deal_id, started_at);
create index if not exists call_recordings_contact_id_idx on public.call_recordings using btree (contact_id);
create index if not exists call_recordings_pending_idx on public.call_recordings using btree (status) where status = 'pending';

alter table public.call_recordings enable row level security;
alter table public.salestrail_sync_state enable row level security;

create policy "Enable read for own, lead owner or admins" on public.call_recordings
    for select to authenticated
    using (
        (select public.crm_role()) = 'admin'
        or sales_id = (select public.current_sales_id())
        or exists (select 1 from public.deals d where d.id = call_recordings.deal_id)
    );

grant all on table public.salestrail_sync_state to service_role;
revoke all on table public.salestrail_sync_state from anon, authenticated;
grant select on table public.call_recordings to authenticated;
grant all on table public.call_recordings to service_role;
grant all on sequence public.call_recordings_id_seq to service_role;
revoke all on table public.call_recordings from anon;
revoke all on sequence public.call_recordings_id_seq from anon, authenticated;

CREATE OR REPLACE FUNCTION "public"."record_salestrail_call"("p_call_id" "text", "p_user_email" "text", "p_phone" "text", "p_is_inbound" boolean, "p_started_at" timestamp with time zone, "p_duration_seconds" integer) RETURNS bigint
    LANGUAGE "plpgsql" SECURITY DEFINER
    SET "search_path" TO ''
    AS $$
declare
    v_digits text := right(regexp_replace(coalesce(p_phone, ''), '\D', '', 'g'), 10);
    v_contact_id bigint;
    v_sales_id bigint;
    v_deal_id bigint;
    v_id bigint;
begin
    -- Too short to identify a lead (service numbers, blank caller id)
    if length(v_digits) < 10 then
        return null;
    end if;

    -- Match on the last 10 digits, so "+91 98765 43210" and "09876543210" agree
    select co.id into v_contact_id
    from public.contacts co
    where co.phone_e164 = p_phone
       or right(regexp_replace(coalesce(co.phone_e164, ''), '\D', '', 'g'), 10) = v_digits
       or exists (
           select 1
           from jsonb_array_elements(coalesce(co.phone_jsonb, '[]'::jsonb)) ph
           where right(regexp_replace(coalesce(ph->>'number', ''), '\D', '', 'g'), 10) = v_digits
       )
    order by (co.phone_e164 = p_phone) desc nulls last, co.id desc
    limit 1;

    -- Not a lead (e.g. a personal call): never stored
    if v_contact_id is null then
        return null;
    end if;

    select s.id into v_sales_id
    from public.sales s
    where lower(s.email) = lower(p_user_email)
       or lower(p_user_email) in (select lower(e) from jsonb_array_elements_text(s.secondary_emails) e)
    order by s.disabled, s.id
    limit 1;

    select d.id into v_deal_id
    from public.deals d
    where v_contact_id = any (d.contact_ids)
    order by (d.archived_at is null) desc, d.updated_at desc
    limit 1;

    insert into public.call_recordings (
        salestrail_call_id, sales_id, contact_id, deal_id, phone_number,
        is_inbound, started_at, duration_seconds
    )
    values (
        p_call_id, v_sales_id, v_contact_id, v_deal_id, p_phone,
        p_is_inbound, p_started_at, greatest(coalesce(p_duration_seconds, 0), 0)
    )
    on conflict (salestrail_call_id) do nothing
    returning id into v_id;

    return v_id;
end;
$$;

revoke all on function public.record_salestrail_call(text, text, text, boolean, timestamp with time zone, integer) from public, anon, authenticated;
grant all on function public.record_salestrail_call(text, text, text, boolean, timestamp with time zone, integer) to service_role;

-- Private bucket: audio is only served through short-lived signed URLs
insert into storage.buckets (id, name, public, allowed_mime_types)
values ('call-recordings', 'call-recordings', false, array['audio/*'])
on conflict (id) do update set public = false, allowed_mime_types = excluded.allowed_mime_types;

create policy "Call recordings read" on storage.objects for select to authenticated using (bucket_id = 'call-recordings' and exists (select 1 from public.call_recordings r where r.storage_path = storage.objects.name));

-- Every 5 minutes, call the salestrail_sync edge function. Its URL and secret
-- are read from Vault (never committed), so nothing runs until they are set:
--   select vault.create_secret('https://<project>.supabase.co/functions/v1/salestrail_sync', 'salestrail_sync_url');
--   select vault.create_secret('<same value as SALESTRAIL_SYNC_SECRET>', 'salestrail_sync_secret');
create extension if not exists pg_net;

do $cron$
begin
  create extension if not exists pg_cron with schema extensions;
  perform cron.unschedule(jobid)
  from cron.job
  where jobname = 'salestrail-sync';
  perform cron.schedule(
    'salestrail-sync',
    '*/5 * * * *',
    $job$
      select net.http_post(
        url := s.url,
        headers := jsonb_build_object('Content-Type', 'application/json', 'x-sync-secret', s.secret),
        body := '{}'::jsonb,
        timeout_milliseconds := 120000
      )
      from (
        select
          (select decrypted_secret from vault.decrypted_secrets where name = 'salestrail_sync_url') as url,
          (select decrypted_secret from vault.decrypted_secrets where name = 'salestrail_sync_secret') as secret
      ) s
      where s.url is not null and s.secret is not null;
    $job$
  );
exception
  when others then
    raise notice 'pg_cron not available; schedule salestrail_sync manually: %', sqlerrm;
end;
$cron$;
