do $cron$
begin
  create extension if not exists pg_cron with schema extensions;
  perform cron.unschedule(jobid)
  from cron.job
  where jobname = 'assign-daily-calls';
  perform cron.schedule(
    'assign-daily-calls',
    '0 3 * * 1-5',
    $job$select public.assign_daily_calls();$job$
  );
exception
  when others then
    raise notice 'pg_cron not available; schedule assign_daily_calls manually: %', sqlerrm;
end;
